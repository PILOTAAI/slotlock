const block = (tokens) =>
  Object.entries(tokens)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join('\n');

/** The CSS: light by default, dark from the system preference unless overridden by data-theme. */
export function tokensCss() {
  return `/* Generated by scripts/sync-content.mjs from src/styles/tokens.mjs. Do not edit. */
:root {
  color-scheme: light;
${block(light)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${block(dark).replace(/^/gm, '  ')}
  }
}
:root[data-theme='dark'] {
  color-scheme: dark;
${block(dark)}
}
`;
}
