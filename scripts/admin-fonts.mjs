#!/usr/bin/env node
// Writes src/admin/fonts.ts: the staff console's two typefaces, Inter and Geist Mono, as the Latin
// woff2 subsets Fontsource publishes (@fontsource-variable/inter and @fontsource-variable/geist-mono,
// pinned in package.json's devDependencies), embedded so the console's Worker serves them from its
// own origin at a hashed path, cached for a year. Both are under the SIL Open Font License 1.1, whose
// text, with each font's copyright line, goes beside the module in src/admin/fonts/.
//
//   node scripts/admin-fonts.mjs           write the module and the licences
//   node scripts/admin-fonts.mjs --check   exit 1 when they are not what the packages make
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const modules = join(root, 'node_modules');

/** Fontsource's Latin range, as its stylesheets give it for these files. */
const LATIN = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';

const FONTS = [
  { family: 'Inter', name: 'inter', pkg: '@fontsource-variable/inter', file: 'files/inter-latin-wght-normal.woff2', licence: 'Inter-OFL.txt' },
  { family: 'Geist Mono', name: 'geist-mono', pkg: '@fontsource-variable/geist-mono', file: 'files/geist-mono-latin-wght-normal.woff2', licence: 'GeistMono-OFL.txt' },
];

export function renderAdminFonts() {
  const files = new Map();
  const entries = FONTS.map((font) => {
    const dir = join(modules, ...font.pkg.split('/'));
    const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    if (manifest.license !== 'OFL-1.1') throw new Error(`${font.pkg} is licensed ${manifest.license}, not OFL-1.1: review it first`);
    const bytes = readFileSync(join(dir, font.file));
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    files.set(join(root, 'src/admin/fonts', font.licence), readFileSync(join(dir, 'LICENSE'), 'utf8'));
    return { ...font, version: manifest.version, path: `/fonts/${font.name}-${hash}.woff2`, base64: bytes.toString('base64') };
  });
  const module = `// Generated by scripts/admin-fonts.mjs: do not edit. ${entries.map((font) => `${font.pkg} ${font.version}`).join(', ')},
// the Latin subset of each as woff2, under the SIL Open Font License 1.1 (src/admin/fonts/).

export interface SlotlockAdminFont {
  family: string;
  /** Where the console serves it: the file's hash is in the name, so it is cached for good. */
  path: string;
  unicodeRange: string;
  /** The woff2 file, base64. */
  base64: string;
}

export const SLOTLOCK_ADMIN_FONTS: readonly SlotlockAdminFont[] = Object.freeze([
${entries.map((font) => `  {
    family: ${JSON.stringify(font.family)},
    path: ${JSON.stringify(font.path)},
    unicodeRange: ${JSON.stringify(LATIN)},
    base64: ${JSON.stringify(font.base64)},
  },`).join('\n')}
]);
`;
  files.set(join(root, 'src/admin/fonts.ts'), module);
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = renderAdminFonts();
  if (process.argv.includes('--check')) {
    const stale = [...files].filter(([path, text]) => {
      try {
        return readFileSync(path, 'utf8') !== text;
      } catch {
        return true;
      }
    });
    for (const [path] of stale) console.error(`${path} is not what scripts/admin-fonts.mjs writes: run it`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [path, text] of files) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
}
